/**
 * One-click setup for OpenCode plugin.
 * Installs/removes a JS plugin at ~/.config/opencode/plugins/event-horizon.ts
 * that forwards OpenCode events to Event Horizon's HTTP server.
 *
 * OpenCode auto-loads .ts files from ~/.config/opencode/plugins/ at startup,
 * in both v1 and v2 — a file plugin needs no `plugin`/`plugins` config entry
 * (spike 0.1: v2 2.1.1 discovered plugins in that dir with no config entry).
 * Users must restart OpenCode after installing the plugin.
 *
 * v1 and v2 have incompatible plugin contracts (v1: default-exported function;
 * v2: default-exported `{ id, setup }` literal), so the installer detects the
 * installed major and writes the matching bundle from `generated/pluginSources`.
 *
 * Never writes ~/.config/opencode/package.json: no dependency is needed, and
 * that file carries the user's own `@opencode-ai/plugin` entry.
 */

import * as vscode from 'vscode';
import * as fsp from 'fs/promises';
import * as path from 'path';
import * as os from 'os';
import { execFile } from 'child_process';
import { getAuthToken } from './eventServer.js';
import { OPENCODE_V1_SOURCE, OPENCODE_V2_SOURCE } from './generated/pluginSources.js';

const PORT = 28765;
const PLUGIN_FILENAME = 'event-horizon.ts';
const TOKEN_PLACEHOLDER = '__EH_AUTH_TOKEN__';
const VERSION_TIMEOUT_MS = 5000;

/** Marker comment so we can identify our plugin file. */
const MARKER = '// @event-horizon/opencode-plugin';

export type OpenCodeMajor = 1 | 2;

function getPluginDir(): string {
  return path.join(os.homedir(), '.config', 'opencode', 'plugins');
}

function getPluginPath(): string {
  return path.join(getPluginDir(), PLUGIN_FILENAME);
}

/** Runs `opencode --version` and resolves its stdout. Injectable so tests never spawn. */
export type ExecVersionFn = () => Promise<string>;

const defaultExecVersion: ExecVersionFn = () =>
  new Promise((resolve, reject) => {
    // Fixed argv, nothing interpolated. On Windows the npm-installed v2 binary
    // is `opencode.cmd`, which can only be launched through cmd.exe — and cmd.exe
    // resolves PATH/PATHEXT the way the user's terminal does, so we detect the
    // binary they would actually run (a plain execFile would only find .exe).
    execFile(
      'opencode',
      ['--version'],
      { timeout: VERSION_TIMEOUT_MS, windowsHide: true, shell: process.platform === 'win32' },
      (err, stdout) => (err ? reject(err) : resolve(String(stdout))),
    );
  });

/** Parses `opencode --version` output ("1.19.1", "opencode v2.1.1") into a supported major. */
export function parseOpenCodeMajor(output: string): OpenCodeMajor | null {
  const m = /(?:^|[^\w.])v?(\d+)\.\d+(?:\.\d+)?/.exec(output.trim());
  if (!m) return null;
  const major = Number(m[1]);
  return major === 1 || major === 2 ? major : null;
}

/** Detects the installed OpenCode major version. Never throws — null when unknown. */
export async function detectOpenCodeMajor(exec: ExecVersionFn = defaultExecVersion): Promise<OpenCodeMajor | null> {
  try {
    return parseOpenCodeMajor(await exec());
  } catch {
    return null;
  }
}

/** Plugin file contents for a major, with the auth token substituted. */
export function buildPluginSource(major: OpenCodeMajor, token: string): string {
  const bundle = major === 2 ? OPENCODE_V2_SOURCE : OPENCODE_V1_SOURCE;
  // The placeholder sits inside a double-quoted JS string literal.
  const escaped = JSON.stringify(token).slice(1, -1);
  const body = bundle.split(TOKEN_PLACEHOLDER).join(escaped);
  return `${MARKER} (opencode v${major})
// Auto-generated by Event Horizon VS Code extension.
// Forwards OpenCode events to the Event Horizon visualization server.
// Do not edit — reinstall from Event Horizon's Connect panel.

${body}`;
}

/** Which plugin contract an installed file implements, or null if unrecognised. */
function installedShape(content: string): OpenCodeMajor | null {
  if (/id:\s*"event-horizon"/.test(content) && /\bsetup\s*\(/.test(content)) return 2;
  if (/\bfunction EventHorizon\s*\(/.test(content)) return 1;
  return null;
}

async function readInstalledPlugin(): Promise<string | null> {
  try {
    const content = await fsp.readFile(getPluginPath(), 'utf8');
    return content.includes(MARKER) ? content : null;
  } catch {
    return null;
  }
}

/**
 * The major to install for. When detection fails (binary not on the extension
 * host's PATH, timeout, unknown major), keep the shape already installed so a
 * working v2 file is never flipped back to v1; otherwise fall back to v1. The v2
 * bundle is not v1-compatible (v1 calls the default export as a function), and
 * v1 is the shape every pre-3.3.0 install already runs.
 */
function resolveTargetMajor(detected: OpenCodeMajor | null, installed: string | null): OpenCodeMajor {
  if (detected) return detected;
  return (installed && installedShape(installed)) || 1;
}

/** Returns true if the Event Horizon plugin file exists (any token version). */
export async function isOpenCodeHooksInstalled(): Promise<boolean> {
  return (await readInstalledPlugin()) !== null;
}

/**
 * Returns true if our plugin file exists but is not exactly what we would write
 * now: wrong shape for the detected OpenCode major (e.g. a v1 file after the user
 * upgraded to v2), stale token, legacy `?token=` auth, or an older bundle.
 * Never throws, including when OpenCode is not installed.
 */
export async function hasStaleOpenCodeHooks(exec?: ExecVersionFn): Promise<boolean> {
  try {
    const content = await readInstalledPlugin();
    if (!content) return false;
    const target = resolveTargetMajor(await detectOpenCodeMajor(exec), content);
    return content !== buildPluginSource(target, getAuthToken() ?? '');
  } catch {
    return false;
  }
}

/** Removes the Event Horizon plugin file. */
export async function removeOpenCodeHooks(): Promise<void> {
  const pluginPath = getPluginPath();
  try {
    const content = await fsp.readFile(pluginPath, 'utf8');
    if (content.includes(MARKER)) {
      await fsp.unlink(pluginPath);
    }
  } catch {
    // Nothing to remove
  }
}

export interface OpenCodeInstallResult {
  /** Major reported by `opencode --version`, or null if it could not be detected. */
  detected: OpenCodeMajor | null;
  /** Plugin contract actually written. */
  written: OpenCodeMajor;
}

/** Writes the Event Horizon plugin file matching the installed OpenCode major. */
export async function setupOpenCodeHooks(exec?: ExecVersionFn): Promise<OpenCodeInstallResult> {
  const dir = getPluginDir();
  await fsp.mkdir(dir, { recursive: true });
  // Remove old .mjs version if present
  const oldMjs = path.join(dir, 'event-horizon.mjs');
  try { await fsp.unlink(oldMjs); } catch { /* ignore */ }
  const detected = await detectOpenCodeMajor(exec);
  const written = resolveTargetMajor(detected, await readInstalledPlugin());
  await fsp.writeFile(getPluginPath(), buildPluginSource(written, getAuthToken() ?? ''), 'utf8');
  if (!detected) {
    void vscode.window.showWarningMessage(
      `Event Horizon: Could not detect your OpenCode version (\`opencode --version\` failed), so the v${written} plugin was installed. If OpenCode does not show up, make sure \`opencode\` is on your PATH and reinstall.`,
    );
  }
  // Keep legacy ~/.opencode/config.json curl hooks (if any) on the current token.
  await updateLegacyOpenCodeConfigHooks();
  return { detected, written };
}

/**
 * Update legacy ~/.opencode/config.json curl hook commands with the current auth
 * token (Bearer header). Only rewrites entries already pointing at Event Horizon
 * and never creates the file. The plugin file itself needs no config entry in
 * either v1 (`plugin`) or v2 (`plugins`) — it is auto-discovered.
 */
async function updateLegacyOpenCodeConfigHooks(): Promise<void> {
  const configPath = path.join(os.homedir(), '.opencode', 'config.json');
  const token = getAuthToken();
  const baseUrl = `http://127.0.0.1:${PORT}/opencode`;
  const authHeader = token ? `-H "Authorization: Bearer ${token}"` : '';
  try {
    const raw = await fsp.readFile(configPath, 'utf8');
    const config = JSON.parse(raw) as Record<string, unknown>;
    const hooks = config.hooks as Record<string, Array<Record<string, unknown>>> | undefined;
    if (!hooks) return;
    let changed = false;
    for (const entries of Object.values(hooks)) {
      for (const entry of entries) {
        if (typeof entry.command === 'string' && entry.command.includes(`127.0.0.1:${PORT}/opencode`)) {
          const newCmd = `curl -s -X POST ${baseUrl} -H "Content-Type: application/json" ${authHeader} --data-binary @-`;
          if (entry.command !== newCmd) {
            entry.command = newCmd;
            changed = true;
          }
        }
      }
    }
    if (changed) {
      await fsp.writeFile(configPath, JSON.stringify(config, null, 2), 'utf8');
    }
  } catch { /* file doesn't exist or not writable — skip */ }
}

/**
 * Register Event Horizon as an MCP server in OpenCode's config.
 * Reads ~/.config/opencode/opencode.json, merges our entry under "mcp".
 */
export async function registerOpenCodeMcpServer(): Promise<void> {
  const configPath = path.join(os.homedir(), '.config', 'opencode', 'opencode.json');
  // v2.0.0: MCP URL no longer carries ?token=. OpenCode's MCP client
  // discovers auth via RFC 9728 .well-known/oauth-protected-resource and
  // obtains JWT access tokens through OAuth 2.1 client_credentials flow.
  const mcpUrl = `http://127.0.0.1:${PORT}/mcp`;

  let config: Record<string, unknown> = {};
  try {
    const raw = await fsp.readFile(configPath, 'utf8');
    config = JSON.parse(raw);
  } catch {
    // File doesn't exist or is invalid — start fresh
  }

  const mcp = (config.mcp ?? {}) as Record<string, unknown>;
  mcp['event-horizon'] = { type: 'remote', url: mcpUrl, enabled: true };
  config.mcp = mcp;

  const dir = path.dirname(configPath);
  await fsp.mkdir(dir, { recursive: true });
  await fsp.writeFile(configPath, JSON.stringify(config, null, 2), 'utf8');
}

export async function runSetupOpenCodeHooks(): Promise<void> {
  try {
    const { detected } = await setupOpenCodeHooks();
    await registerOpenCodeMcpServer();
    const v2Note = detected === 1
      ? ' OpenCode v2 is supported too — reinstall from the Connect panel after upgrading.'
      : '';
    void vscode.window.showInformationMessage(
      `Event Horizon: OpenCode plugin + MCP tools installed! Restart OpenCode to load the plugin and see your agent appear.${v2Note}`,
    );
  } catch (e) {
    const msg = e instanceof Error ? e.message : String(e);
    void vscode.window.showErrorMessage(`Event Horizon: Failed to install OpenCode plugin — ${msg}`);
  }
}
