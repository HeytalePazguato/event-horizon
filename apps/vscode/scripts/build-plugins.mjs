#!/usr/bin/env node
/**
 * Bundle the OpenCode plugins and inline them into a generated TS module.
 *
 * The plugins run inside OpenCode, not VS Code, so they are not part of the
 * extension bundle. The extension installer writes them to disk at setup time;
 * to avoid shipping loose files we embed the bundled source as string
 * constants in src/generated/pluginSources.ts (gitignored).
 *
 * The literal token `__EH_AUTH_TOKEN__` must survive bundling untouched — the
 * installer substitutes it when writing the plugin. Output is not minified so
 * users can read the installed file.
 */

import * as esbuild from 'esbuild';
import { mkdir, writeFile } from 'node:fs/promises';

const PLUGINS = [
  { entry: 'plugins/opencode/v1/plugin.ts', name: 'OPENCODE_V1_SOURCE' },
  { entry: 'plugins/opencode/v2/plugin.ts', name: 'OPENCODE_V2_SOURCE' },
];

const TOKEN = '__EH_AUTH_TOKEN__';

let out =
  '// AUTO-GENERATED by scripts/build-plugins.mjs — DO NOT EDIT.\n' +
  '// Edit the sources under plugins/ and re-run the build.\n\n';

for (const { entry, name } of PLUGINS) {
  const result = await esbuild.build({
    entryPoints: [entry],
    bundle: true,
    write: false,
    format: 'esm',
    platform: 'node',
    minify: false,
    legalComments: 'none',
  });
  const text = result.outputFiles[0].text;
  if (!text.includes(TOKEN)) {
    throw new Error(`${entry}: bundled output lost the ${TOKEN} placeholder`);
  }
  out += `export const ${name} = ${JSON.stringify(text)};\n\n`;
}

await mkdir('src/generated', { recursive: true });
await writeFile('src/generated/pluginSources.ts', out.trimEnd() + '\n');
